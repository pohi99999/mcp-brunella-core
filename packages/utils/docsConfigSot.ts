export type DocsConfigHealthStatus = "healthy" | "warning" | "critical";
export type DocsConfigSeverity = "low" | "medium" | "high" | "critical";

export interface MarkerDefinition {
  id: string;
  pattern: RegExp;
}

export interface SurfaceDefinition {
  name: string;
  path: string;
  kind: "doc" | "config" | "script";
  required: boolean;
  markers?: MarkerDefinition[];
}

export interface SurfaceSummary {
  name: string;
  path: string;
  kind: "doc" | "config" | "script";
  required: boolean;
  present: boolean;
  characters: number;
  lines: number;
  matchedMarkers: string[];
  expectedMarkers: string[];
}

export interface RuntimeKeySource {
  source: string;
  keys: string[];
}

export interface ConfigKeyCoverage {
  key: string;
  sources: string[];
  inDocs: string[];
  inExample: boolean;
  inYaml: boolean;
}

export interface DocsConfigSotSnapshot {
  checkedAt: string;
  rootDir: string;
  documents: {
    surfaces: SurfaceSummary[];
    requiredCount: number;
    presentRequiredCount: number;
    managedCount: number;
    managedHealthyCount: number;
    coveragePercent: number;
    managedCoveragePercent: number;
    missingRequired: string[];
    missingManagedMarkers: string[];
  };
  config: {
    surfaces: SurfaceSummary[];
    runtimeKeySources: RuntimeKeySource[];
    runtimeKeys: string[];
    exampleKeys: string[];
    yamlBindings: string[];
    keyCoverage: ConfigKeyCoverage[];
    docsKeyCoveragePercent: number;
    exampleKeyCoveragePercent: number;
    missingFromDocs: ConfigKeyCoverage[];
    missingFromExample: ConfigKeyCoverage[];
    yamlBindingsMissingFromRuntime: string[];
  };
  summary: {
    score: number;
    status: DocsConfigHealthStatus;
    docsStatus: DocsConfigHealthStatus;
    configStatus: DocsConfigHealthStatus;
  };
  warnings: string[];
}

